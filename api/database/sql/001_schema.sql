-- GottaDoIt — esquema completo (PostgreSQL 15+ / Supabase)
--
-- Corre com um papel de administração (dono das tabelas). A API liga-se com
-- o papel `gottadoit_app`, que tem de existir antes e NÃO pode ter BYPASSRLS.
--
-- Isolamento por utilizador: em cada pedido a API define, dentro de uma
-- transação, `set_config('app.user_id', '<uuid>', true)`. As políticas RLS
-- comparam `user_id` com esse valor. Sem valor definido, não se vê nada.

-- ---------------------------------------------------------------------------
-- Utilizadores e tokens (sem RLS: lidos antes de se saber quem é o utilizador)
-- ---------------------------------------------------------------------------

CREATE TABLE users (
    id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name                  text        NOT NULL,
    email                 text        NOT NULL,
    password              text        NOT NULL,
    timezone              text        NOT NULL DEFAULT 'Europe/Lisbon',
    week_start            smallint    NOT NULL DEFAULT 1 CHECK (week_start IN (0, 1)), -- 0 domingo, 1 segunda
    theme                 text        NOT NULL DEFAULT 'system' CHECK (theme IN ('system', 'light', 'dark')),
    notification_settings jsonb       NOT NULL DEFAULT
        '{"push": true, "email": false, "daily_digest": false, "daily_digest_time": "08:00"}'::jsonb,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_email_unique ON users (lower(email));

CREATE TABLE personal_access_tokens (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tokenable_type text        NOT NULL,
    tokenable_id   uuid        NOT NULL,
    name           text        NOT NULL,
    token          varchar(64) NOT NULL UNIQUE,
    abilities      text,
    last_used_at   timestamptz,
    expires_at     timestamptz,
    created_at     timestamptz,
    updated_at     timestamptz
);

CREATE INDEX personal_access_tokens_tokenable_index
    ON personal_access_tokens (tokenable_type, tokenable_id);

-- ---------------------------------------------------------------------------
-- Projetos e secções
-- ---------------------------------------------------------------------------

CREATE TABLE projects (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id     uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    parent_id   uuid        REFERENCES projects (id) ON DELETE CASCADE,
    name        text        NOT NULL,
    color       text        NOT NULL DEFAULT '#808080' CHECK (color ~ '^#[0-9a-fA-F]{6}$'),
    icon        text,
    view        text        NOT NULL DEFAULT 'list' CHECK (view IN ('list', 'board')),
    is_favorite boolean     NOT NULL DEFAULT false,
    position    integer     NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX projects_user_parent_position_index ON projects (user_id, parent_id, position);

CREATE TABLE sections (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    project_id uuid        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    name       text        NOT NULL,
    position   integer     NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX sections_project_position_index ON sections (project_id, position);

-- ---------------------------------------------------------------------------
-- Tarefas
-- ---------------------------------------------------------------------------

CREATE TABLE tasks (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    project_id      uuid        REFERENCES projects (id) ON DELETE CASCADE, -- NULL = Caixa de Entrada
    section_id      uuid        REFERENCES sections (id) ON DELETE SET NULL,
    parent_task_id  uuid        REFERENCES tasks (id) ON DELETE CASCADE,    -- subtarefas recursivas
    title           text        NOT NULL CHECK (length(title) BETWEEN 1 AND 500),
    description     text,                                                    -- Markdown básico
    due_date        date,                                                    -- no fuso do utilizador
    due_time        time,                                                    -- no fuso do utilizador
    recurrence_rule text,                                                    -- RRULE reduzido
    recurrence_text text,                                                    -- o que o utilizador escreveu
    priority        smallint    NOT NULL DEFAULT 4 CHECK (priority BETWEEN 1 AND 4), -- 1 = P1
    is_completed    boolean     NOT NULL DEFAULT false,
    completed_at    timestamptz,
    position        integer     NOT NULL DEFAULT 0,
    deleted_at      timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tasks_time_needs_date CHECK (due_time IS NULL OR due_date IS NOT NULL),
    CONSTRAINT tasks_recurrence_needs_date CHECK (recurrence_rule IS NULL OR due_date IS NOT NULL),
    CONSTRAINT tasks_not_own_parent CHECK (parent_task_id IS NULL OR parent_task_id <> id)
);

-- "Hoje", "Em atraso" e "Em breve": tarefas abertas por utilizador e data.
CREATE INDEX tasks_open_by_due_index ON tasks (user_id, due_date, due_time)
    WHERE NOT is_completed AND deleted_at IS NULL;

-- Listas de projeto, Caixa de Entrada e quadro Kanban.
CREATE INDEX tasks_project_section_position_index ON tasks (user_id, project_id, section_id, position)
    WHERE deleted_at IS NULL;

CREATE INDEX tasks_parent_index ON tasks (parent_task_id);
CREATE INDEX tasks_section_index ON tasks (section_id);

-- Histórico de concluídas e métricas de produtividade.
CREATE INDEX tasks_completed_index ON tasks (user_id, completed_at)
    WHERE is_completed;

-- ---------------------------------------------------------------------------
-- Etiquetas (N:N com tarefas)
-- ---------------------------------------------------------------------------

CREATE TABLE labels (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       text        NOT NULL,
    color      text        NOT NULL DEFAULT '#808080' CHECK (color ~ '^#[0-9a-fA-F]{6}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX labels_user_name_unique ON labels (user_id, lower(name));

CREATE TABLE task_labels (
    task_id  uuid NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    label_id uuid NOT NULL REFERENCES labels (id) ON DELETE CASCADE,
    user_id  uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (task_id, label_id)
);

CREATE INDEX task_labels_label_index ON task_labels (label_id);

-- ---------------------------------------------------------------------------
-- Lembretes
-- ---------------------------------------------------------------------------

CREATE TABLE reminders (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    task_id        uuid        NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    type           text        NOT NULL CHECK (type IN ('absolute', 'relative')),
    remind_at      timestamptz,           -- absolute: data/hora exata
    minutes_before integer,               -- relative: minutos antes do vencimento
    fire_at        timestamptz,           -- instante calculado pela API; é o que o worker lê
    is_sent        boolean     NOT NULL DEFAULT false,
    sent_at        timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT reminders_type_fields CHECK (
        (type = 'absolute' AND remind_at IS NOT NULL AND minutes_before IS NULL)
        OR (type = 'relative' AND minutes_before IS NOT NULL AND minutes_before >= 0 AND remind_at IS NULL)
    )
);

-- O worker corre a cada minuto: lembretes por enviar, por ordem de disparo.
CREATE INDEX reminders_pending_index ON reminders (fire_at) WHERE NOT is_sent;
CREATE INDEX reminders_task_index ON reminders (task_id);

-- ---------------------------------------------------------------------------
-- Registo de atividade
-- ---------------------------------------------------------------------------

CREATE TABLE activity_log (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    task_id    uuid        REFERENCES tasks (id) ON DELETE SET NULL,
    action     text        NOT NULL CHECK (action IN
        ('created', 'updated', 'completed', 'reopened', 'deleted', 'restored', 'rescheduled')),
    payload    jsonb       NOT NULL DEFAULT '{}'::jsonb,
    -- clock_timestamp() e não now(): várias linhas da mesma transação ficam por ordem.
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX activity_log_user_created_index ON activity_log (user_id, created_at DESC);
CREATE INDEX activity_log_task_created_index ON activity_log (task_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Subscrições Web Push
-- ---------------------------------------------------------------------------

CREATE TABLE push_subscriptions (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    endpoint   text        NOT NULL UNIQUE,
    p256dh     text        NOT NULL,
    auth       text        NOT NULL,
    user_agent text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX push_subscriptions_user_index ON push_subscriptions (user_id);

-- ---------------------------------------------------------------------------
-- Permissões e Row-Level Security
-- ---------------------------------------------------------------------------

GRANT USAGE ON SCHEMA public TO gottadoit_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO gottadoit_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO gottadoit_app;

-- FORCE: as políticas aplicam-se também ao dono das tabelas.
-- As políticas valem só para `gottadoit_app`; qualquer outro papel sem
-- BYPASSRLS (por exemplo `anon` e `authenticated` do Supabase) não vê nada.
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'projects', 'sections', 'tasks', 'labels', 'task_labels',
        'reminders', 'activity_log', 'push_subscriptions'
    ]
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format(
            'CREATE POLICY %I ON %I FOR ALL TO gottadoit_app
                 USING (user_id = nullif(current_setting(''app.user_id'', true), '''')::uuid)
                 WITH CHECK (user_id = nullif(current_setting(''app.user_id'', true), '''')::uuid)',
            t || '_owner', t
        );
    END LOOP;
END $$;
